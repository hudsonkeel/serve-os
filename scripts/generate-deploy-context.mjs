#!/usr/bin/env node
// Captures Netlify's BUILD-time-only deploy-context env vars (DEPLOY_PRIME_URL, CONTEXT) into a
// generated source file, because Netlify does NOT forward them into a Function's runtime
// process.env (only URL/SITE_NAME/SITE_ID are runtime-available — see
// lib/assessmentIntelligence/generatedDeployContext.ts's own header comment).
//
// Runs BEFORE `next build` (see package.json's "build" script) so both the Next.js server
// bundle (which pulls this file in via pipeline.ts, used by the scheduled dispatcher's logic)
// and Netlify's separate bundling of netlify/functions/*.mts see the same already-populated
// file — both happen within one overall Netlify build, sharing one filesystem checkout, which is
// the only place DEPLOY_PRIME_URL and CONTEXT actually exist in process.env at all.
//
// Outside a real Netlify build (local dev, a plain `next build` on a laptop), every captured
// value is genuinely absent, so this intentionally writes nulls back — resolveSiteBaseUrl() then
// fails closed rather than guessing, which is correct: a local run must never be able to invoke
// a real deployed background worker. Running this script locally is always a safe no-op diff
// against the committed file (both are all-null), so it never dirties a developer's tree.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, "..", "lib", "assessmentIntelligence", "generatedDeployContext.ts");

const context = process.env.CONTEXT ?? null;
const deployPrimeUrl = process.env.DEPLOY_PRIME_URL ?? null;

const contents = `// AUTO-GENERATED by scripts/generate-deploy-context.mjs at build time — do not edit by hand.
// Regenerated on every \`npm run build\` from Netlify's BUILD-time-only DEPLOY_PRIME_URL/CONTEXT
// env vars. Committed here with null defaults for local/dev runs (a plain \`next build\` on a
// laptop, or this test suite, never regenerates this file), where every value below is genuinely
// absent — see resolveSiteBaseUrl() in pipeline.ts for why that must mean "fail closed," not
// "fall back to something else."
//
// WHY a generated file instead of just reading process.env at runtime: Netlify's own docs
// confirm only URL, SITE_NAME, and SITE_ID are automatically forwarded into a Netlify Function's
// RUNTIME process.env — DEPLOY_PRIME_URL and CONTEXT are build-time-only and are simply absent
// by the time any Function (Scheduled, Background, or the Next.js Runtime's own Server Action
// handler) actually runs. And URL alone is not safe to use for this purpose: it is always the
// site's PRODUCTION address regardless of deploy context — a Deploy Preview or branch-deploy
// dispatcher that fell back to it would silently invoke production's background worker instead
// of its own (production may not even have this feature yet). This file captures the correct
// value once, at build time, so it survives into runtime as a literal instead of being guessed.
export interface GeneratedDeployContext {
  context: string | null;
  deployPrimeUrl: string | null;
}

export const GENERATED_DEPLOY_CONTEXT: GeneratedDeployContext = ${JSON.stringify({ context, deployPrimeUrl }, null, 2)};
`;

writeFileSync(outPath, contents, "utf8");
console.log(`[generate-deploy-context] wrote ${outPath} (context=${context ?? "null"}, deployPrimeUrl=${deployPrimeUrl ?? "null"})`);
