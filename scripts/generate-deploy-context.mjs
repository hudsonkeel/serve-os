#!/usr/bin/env node
// Captures Netlify's BUILD-time-only deploy-context env vars (DEPLOY_PRIME_URL, CONTEXT, URL) into
// a generated source file, because Netlify does NOT forward DEPLOY_PRIME_URL/CONTEXT into a
// Function's runtime process.env (only URL/SITE_NAME/SITE_ID are runtime-available — see
// lib/assessmentIntelligence/generatedDeployContext.ts's own header comment for the doc citations).
//
// Runs BEFORE `next build` (see package.json's "build" script: this script, then `next build`) so
// both the Next.js server bundle (which pulls this file in via pipeline.ts, used by the admin
// Server Action diagnostic) and Netlify's separate esbuild bundling of netlify/functions/*.ts (the
// scheduled dispatcher) see the same already-populated file — both bundling phases run within one
// overall Netlify build, sharing one filesystem checkout, which is the one place DEPLOY_PRIME_URL
// and CONTEXT actually exist in process.env at all.
//
// Outside a real Netlify build (local dev, a plain `next build` on a laptop), every captured value
// is genuinely absent, so this intentionally writes nulls back — resolveSiteBaseUrl() then fails
// closed rather than guessing, which is correct: a local run must never be able to invoke a real
// deployed background worker. This also means running this script locally is always a safe no-op
// diff against the committed file (both are all-null), so it never dirties a developer's tree.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, "..", "lib", "assessmentIntelligence", "generatedDeployContext.ts");

const context = process.env.CONTEXT ?? null;
const deployPrimeUrl = process.env.DEPLOY_PRIME_URL ?? null;
const url = process.env.URL ?? null;

const contents = `// AUTO-GENERATED by scripts/generate-deploy-context.mjs at build time — do not edit by hand.
// Regenerated on every \`npm run build\` from Netlify's BUILD-time-only DEPLOY_PRIME_URL/CONTEXT/URL
// env vars. Committed here with null defaults for local/dev runs (a plain \`next build\` on a
// laptop, or this test suite, never regenerates this file), where every value below is genuinely
// absent — see resolveSiteBaseUrl() in pipeline.ts for why that must mean "fail closed," not "fall
// back to something else."
//
// WHY a generated file instead of just reading process.env at runtime: confirmed directly against
// Netlify's own docs (https://docs.netlify.com/build/functions/environment-variables/) that only
// URL, SITE_NAME, and SITE_ID are automatically forwarded into a Netlify Function's RUNTIME
// process.env — DEPLOY_PRIME_URL and CONTEXT are build-time-only and are simply absent by the time
// any Function (Scheduled, Background, or the Next.js Runtime's own Server Action handler) actually
// runs. The Netlify Function \`Context\` object (the second handler argument) doesn't fill this gap
// either — confirmed via Netlify's Functions API docs that \`context.site.url\` is the production URL
// only, and \`context.deploy\` carries no URL field at all. So the ONLY point at which
// DEPLOY_PRIME_URL/CONTEXT are ever actually available is during the build step itself — this file
// captures them then, once, so the correct value survives into runtime as a literal.
export interface GeneratedDeployContext {
  context: string | null;
  deployPrimeUrl: string | null;
  url: string | null;
}

export const GENERATED_DEPLOY_CONTEXT: GeneratedDeployContext = ${JSON.stringify({ context, deployPrimeUrl, url }, null, 2)};
`;

writeFileSync(outPath, contents, "utf8");
console.log(
  `[generate-deploy-context] wrote ${outPath} (context=${context ?? "null"}, deployPrimeUrl=${deployPrimeUrl ?? "null"}, url=${url ?? "null"})`
);
